from sqlalchemy import desc, select
from sqlalchemy.orm import Session

from app.models.prediction import Prediction
from app.repositories.base import BaseRepository


class PredictionRepository(BaseRepository[Prediction]):
    """Repository for Prediction database operations."""

    def __init__(
        self,
        db: Session,
    ) -> None:
        super().__init__(
            db=db,
            model=Prediction,
        )

    def get_by_company(
        self,
        company_id: int,
    ) -> list[Prediction]:
        """Retrieve all predictions for a company."""

        statement = select(Prediction).where(Prediction.company_id == company_id)

        return list(self.db.scalars(statement).all())

    def get_latest_prediction(
        self,
        company_id: int,
    ) -> Prediction | None:
        """Retrieve the latest prediction for a company."""

        statement = (
            select(Prediction)
            .where(Prediction.company_id == company_id)
            .order_by(desc(Prediction.prediction_date))
        )

        return self.db.scalars(statement).first()

    def get_by_prediction_label(
        self,
        prediction_label: str,
    ) -> list[Prediction]:
        """Retrieve predictions with a specific prediction label."""

        statement = select(Prediction).where(
            Prediction.prediction_label == prediction_label
        )

        return list(self.db.scalars(statement).all())

    def get_by_model_version(
        self,
        model_version: str,
    ) -> list[Prediction]:
        """Retrieve predictions generated by a specific model version."""

        statement = select(Prediction).where(Prediction.model_version == model_version)

        return list(self.db.scalars(statement).all())
