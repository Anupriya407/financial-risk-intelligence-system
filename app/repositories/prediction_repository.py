from sqlalchemy import desc, select
from sqlalchemy.orm import Session

from app.models.prediction import Prediction
from app.repositories.base import BaseRepository


class PredictionRepository(BaseRepository[Prediction]):
    """Repository for Prediction database operations."""

    def __init__(
        self,
        db: Session,
    ) -> None:
        super().__init__(
            db=db,
            model=Prediction,
        )

    def get_by_risk_assessment(
        self,
        risk_assessment_id: int,
    ) -> list[Prediction]:
        """Retrieve all predictions for a risk assessment."""

        statement = select(Prediction).where(Prediction.risk_assessment_id == risk_assessment_id)

        return list(self.db.scalars(statement).all())

    def get_latest_prediction(
        self,
        risk_assessment_id: int,
    ) -> Prediction | None:
        """Retrieve the latest prediction for a risk assessment."""

        statement = (
            select(Prediction)
            .where(Prediction.risk_assessment_id == risk_assessment_id)
            .order_by(desc(Prediction.created_at))
        )

        return self.db.scalars(statement).first()

    def get_by_predicted_class(
        self,
        predicted_class: str,
    ) -> list[Prediction]:
        """Retrieve predictions by predicted class."""

        statement = select(Prediction).where(Prediction.predicted_class == predicted_class)

        return list(self.db.scalars(statement).all())

    def get_by_model_version(
        self,
        model_version: str,
    ) -> list[Prediction]:
        """Retrieve predictions generated by a specific model version."""

        statement = select(Prediction).where(Prediction.model_version == model_version)

        return list(self.db.scalars(statement).all())

    def get_by_model_name(
        self,
        model_name: str,
    ) -> list[Prediction]:
        """Retrieve predictions generated by a specific model."""

        statement = select(Prediction).where(Prediction.model_name == model_name)

        return list(self.db.scalars(statement).all())
